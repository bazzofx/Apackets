def _details(rows: list[dict]) -> dict[str, dict]:
    return {row["protocol"]: json.loads(row["detail"]) for row in rows}


def _flag_map(rows: list[dict]) -> dict[str, list[str]]:
    return {row["protocol"]: json.loads(row["flags"]) for row in rows}


def _codes(flags: list[str]) -> list[str]:
    return [flag.split(":", 1)[0] for flag in flags]


def _session(**overrides) -> protocol_analyzer.Session:
    session = protocol_analyzer.Session(protocol="smtp")
    session.client = protocol_analyzer.Endpoint("10.0.0.1", 40000)
    session.server = protocol_analyzer.Endpoint("10.0.0.2", 25)
    session.first_frame, session.last_frame = 1, 2
    session.start_time, session.end_time, session.duration = 100.0, 101.0, 1.0
    session.packets, session.bytes = 10, 1000
    for name, value in overrides.items():
        setattr(session, name, value)
    return session


