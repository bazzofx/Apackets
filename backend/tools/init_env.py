"""Fill the OS-specific Wireshark paths into the repository's ``.env``.

The application auto-detects TShark, but an explicit path makes a local run
independent of ``PATH``. This script chooses the default installation for the
current operating system, keeps any value already present, and writes the
missing keys:

    python backend/tools/init_env.py
    python backend/tools/init_env.py --force   # replace existing paths

Run it from any directory. Docker does not need this file: the image installs
TShark and resolves it from ``/usr/bin``.
"""

from __future__ import annotations

import argparse
import os
import platform
import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_ENV = REPO_ROOT / ".env"
EXAMPLE_ENV = REPO_ROOT / ".env.example"

PATHS = {
    "tshark": "SHADOWPACKETS_TSHARK_PATH",
    "capinfos": "SHADOWPACKETS_CAPINFOS_PATH",
}


def _candidate_paths(name: str, system: str) -> list[Path]:
    """Default install locations, most specific first."""
    suffix = ".exe" if system == "Windows" else ""
    binary = f"{name}{suffix}"
    candidates: list[Path] = []

    if system == "Windows":
        program_files = [
            os.environ.get("ProgramFiles"),
            os.environ.get("ProgramFiles(x86)"),
            r"C:\Program Files",
            r"C:\Program Files (x86)",
        ]
        for root in program_files:
            if root:
                candidates.append(Path(root) / "Wireshark" / binary)
    elif system == "Linux":
        for root in ("/usr/bin", "/usr/local/bin", "/snap/bin"):
            candidates.append(Path(root) / binary)
    elif system == "Darwin":
        for root in (
            "/opt/homebrew/bin",
            "/usr/local/bin",
            "/Applications/Wireshark.app/Contents/MacOS",
        ):
            candidates.append(Path(root) / binary)

    return candidates


def find_binary(name: str, system: str) -> Path | None:
    """Prefer the binary on PATH, then this OS's default install directory."""
    found = shutil.which(name)
    if found:
        return Path(found)
    for candidate in _candidate_paths(name, system):
        if candidate.is_file():
            return candidate
    return None


def _is_setting(line: str) -> tuple[str, str] | None:
    stripped = line.strip()
    if not stripped or stripped.startswith("#") or "=" not in stripped:
        return None
    key, _, value = stripped.partition("=")
    key = key.strip()
    if key.startswith("export "):
        key = key[len("export ") :].strip()
    return key, value.strip()


def existing_settings(lines: list[str]) -> dict[str, str]:
    settings: dict[str, str] = {}
    for line in lines:
        parsed = _is_setting(line)
        if parsed is not None:
            key, value = parsed
            settings[key] = value.strip().strip('"').strip("'")
    return settings


def set_setting(lines: list[str], key: str, value: str) -> bool:
    """Replace ``key`` in place, or append it. Returns whether a line was replaced."""
    # Single quotes stop python-dotenv interpreting Windows backslashes: a
    # double-quoted "C:\...\tshark.exe" would turn the \t into a tab.
    replacement = f"{key}='{value}'"
    for index, line in enumerate(lines):
        parsed = _is_setting(line)
        if parsed is not None and parsed[0] == key:
            lines[index] = replacement
            return True
    lines.append(replacement)
    return False


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--env",
        type=Path,
        default=DEFAULT_ENV,
        help=f"environment file to update (default: {DEFAULT_ENV})",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="replace existing SHADOWPACKETS_*_PATH values",
    )
    args = parser.parse_args()

    system = platform.system()
    env_path: Path = args.env
    if env_path.exists():
        lines = env_path.read_text(encoding="utf-8").splitlines()
    elif EXAMPLE_ENV.exists():
        lines = EXAMPLE_ENV.read_text(encoding="utf-8").splitlines()
    else:
        lines = [
            "# ShadowPackets configuration.",
            "# Generated by backend/tools/init_env.py.",
        ]
    settings = existing_settings(lines)

    changed = False
    missing: list[str] = []
    for name, key in PATHS.items():
        current = settings.get(key, "")
        if current and not args.force:
            print(f"keep {key}={current}")
            continue

        found = find_binary(name, system)
        if found is None:
            missing.append(name)
            print(f"not found: {name} (leave {key} unset)")
            continue

        set_setting(lines, key, str(found))
        settings[key] = str(found)
        changed = True
        print(f"set {key}={found}")

    if changed:
        env_path.parent.mkdir(parents=True, exist_ok=True)
        env_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"updated {env_path}")
    else:
        print(f"no changes to {env_path}")

    if missing:
        print(
            "Wireshark was not found for this OS. Install it, or set the "
            "missing path(s) explicitly in .env."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
