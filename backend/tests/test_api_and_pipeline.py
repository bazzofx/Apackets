def test_malformed_capture_does_not_crash_the_pipeline(client, malformed_capture):
    """Either a clean rejection or a completed analysis — never a 500."""
    import time

    with open(malformed_capture, "rb") as handle:
        response = client.post(
            "/api/analyses",
            files={"file": (malformed_capture.name, handle, "application/octet-stream")},
        )

    if response.status_code != 202:
        assert response.status_code in {400, 415}
        assert "error" in response.json()
        return

    analysis_id = response.json()["id"]
    deadline = time.monotonic() + 120
    while time.monotonic() < deadline:
        detail = client.get(f"/api/analyses/{analysis_id}").json()
        if detail["status"] in {"completed", "failed", "cancelled"}:
            assert detail["status"] in {"completed", "failed"}
            return
        time.sleep(0.2)
    raise AssertionError("malformed capture analysis never settled")


