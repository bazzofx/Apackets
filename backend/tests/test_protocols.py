def test_flags_are_ordered_most_serious_first_and_capped():
    """§4's ordering is what a reader sees; the cap stays defensive above it.

    The two port-based flags are mutually exclusive on one row (`no_encryption_upgrade`
    needs a port that expects an upgrade, `unusual_port` a port outside the table), so the
    most a session carries is seven - which is why this asserts the ordering, not the cap.
    """
    facts = protocol_analyzer.Facts(
        commands=999, username="alice", password=True, auth_failures=5,
        anonymous=True, legacy_dialect=True, signing_required=False,
    )
    heavy = {
        "protocol": "ftp",
        "bytes": protocol_analyzer.LARGE_TRANSFER_BYTES + 1,
        "duration": float(protocol_analyzer.LONG_SESSION_SECONDS) + 1,
        "facts": facts,
    }

    on_port_21 = protocol_analyzer.compute_flags(
        _session(server=protocol_analyzer.Endpoint("10.0.0.2", 21), **heavy)
    )
    assert _codes(on_port_21) == [
        "cleartext_credentials", "auth_failures", "anonymous_login",
        "no_encryption_upgrade", "large_transfer", "many_commands", "long_session",
    ]

    on_an_odd_port = protocol_analyzer.compute_flags(
        _session(server=protocol_analyzer.Endpoint("10.0.0.2", 2121), **heavy)
    )
    codes = _codes(on_an_odd_port)
    assert codes == [
        "cleartext_credentials", "auth_failures", "anonymous_login",
        "unusual_port", "large_transfer", "many_commands", "long_session",
    ]
    assert len(codes) <= protocol_analyzer.FLAG_CAP == 10
    assert on_port_21[0].startswith("cleartext_credentials:")

    # The order is the contract's order, for any set of codes that fires.
    assert [code for code in protocol_analyzer.FLAG_ORDER if code in set(codes)] == codes


