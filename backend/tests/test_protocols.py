def test_ssh_identifications_do_not_decide_which_side_serves(extract, protocol_captures):
    """Both endpoints send an identification string, and the client's comes first.

    §1.2 lists the SSH banner under rule 2. Taken literally - the first banner is the
    server's - this capture would invert the roles, because the client announces itself in
    the first frame. Off §1.2's table the session therefore falls to rule 3, whose answer
    is the connecting side, and the banners are still recorded per direction.
    """
    rows, _ = extract(protocol_captures["ssh_offport"])
    ssh = rows[0]
    assert ssh["server_ip"] == "10.10.0.20" and ssh["server_port"] == 2222
    assert ssh["client_ip"] == "10.10.0.10" and ssh["client_port"] == 40233
    assert "rule 3" in ssh["note"] and "first frame" in ssh["note"]

    detail = json.loads(ssh["detail"])
    assert detail["client_banner"] == "SSH-2.0-OpenSSH_9.6"
    assert detail["server_banner"].startswith("SSH-2.0-OpenSSH_9.6p1")


