def test_no_encryption_upgrade_is_scoped_to_the_ports_that_expect_one():
    """25 and 587 (SMTP), 110, 143, 21 fire; implicit TLS and odd ports do not."""
    fires = {
        25: "smtp",
        587: "smtp",
        110: "pop3",
        143: "imap",
        21: "ftp",
    }
    for port, protocol in fires.items():
        session = _session(
            protocol=protocol, server=protocol_analyzer.Endpoint("10.0.0.2", port)
        )
        upgrade = [
            flag
            for flag in protocol_analyzer.compute_flags(session)
            if flag.startswith("no_encryption_upgrade")
        ]
        assert upgrade == [
            f"no_encryption_upgrade: no STARTTLS/STLS/AUTH TLS exchange was seen on port {port}"
        ], port

    # Implicit TLS carries the protocol from its first byte, so the flag has nothing to
    # say there; an odd port is not a session §4 expects an upgrade on either.
    for port in (465, 995, 993, 2525):
        session = _session(server=protocol_analyzer.Endpoint("10.0.0.2", port))
        assert not [
            flag
            for flag in protocol_analyzer.compute_flags(session)
            if flag.startswith("no_encryption_upgrade")
        ], port

    upgraded = _session(facts=protocol_analyzer.Facts(tls_upgrade=True))
    assert not [
        flag
        for flag in protocol_analyzer.compute_flags(upgraded)
        if flag.startswith("no_encryption_upgrade")
    ]


