@pytest.mark.skipif(not REAL_LAB09.is_file(), reason="lab-09 capture is not present")
def test_real_lab09_capture_smtp_and_smb(extract):
    rows, stats = extract(REAL_LAB09)

    smtp_rows = [row for row in rows if row["protocol"] == "smtp"]
    smb_rows = [row for row in rows if row["protocol"] == "smb"]
    assert len(smtp_rows) == 7
    assert len(smb_rows) == 7
    assert sum(row["packets"] for row in smtp_rows) == 147      # every SMTP frame
    assert sum(row["packets"] for row in smb_rows) == 118       # 6 SMB1 + 112 SMB2

    # §4's port scoping on real traffic: 587 is submission, so it is not unusual, and a
    # session there that never upgraded is readable - both findings belong on the row.
    for row in smtp_rows:
        flags = json.loads(row["flags"])
        codes = _codes(flags)
        assert row["server_port"] == 587
        assert "unusual_port" not in codes
        assert "cleartext_credentials" in codes
        upgrade = next(flag for flag in flags if flag.startswith("no_encryption_upgrade"))
        assert upgrade.endswith("on port 587")

    first = json.loads(smtp_rows[0]["detail"])
    assert first["auth_username"] == "sales.del@macwinlogistics.in"
    assert first["helo"] == "Beijing-5cd1-PC"
    assert first["data_blocks"] == 1
    assert "220" in first["response_codes"]
    assert any(flag.startswith("cleartext_credentials:") for flag in json.loads(smtp_rows[0]["flags"]))

    smb = json.loads(next(row for row in smb_rows if row["stream_id"] == 13)["detail"])
    assert smb["dialects"] == ["SMB 2.1"]
    assert smb["trees"] == ["\\\\PizzaJukebox-DC.pizzajukebox.com\\sysvol"]
    assert smb["signing_required"] is True
    assert smb["statuses"]["STATUS_SUCCESS"] >= 1
    assert stats["protocol_sessions"] == len(rows)


